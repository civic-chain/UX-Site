// Builds public/how-diagram.html, the "Money Moves" animation shown in the
// landing's #record-flow iframe (and on /how).
//
//   npm run build:how-diagram
//
// Output = src/base.html (the original dark animation, untouched) plus:
//   1. three small text swaps so it opens on "Through Civic-Chain"
//      (?mode=old still opens on Legacy System);
//   2. one <style id="variant-skin"> before </head>: light-base.css (dark-on-
//      light), keycap.css (keycap cards; Legacy = aged paper), civic-ink.css
//      (Civic-Chain = deep ink, scoped to html[data-cc="ink"]);
//   3. data-cc="ink" on <html>.
// The animation's markup, script and timing are not changed.
//
// Edit the files in src/, never public/how-diagram.html. {{A}} in the CSS is the
// texture folder, public/how-diagram-assets/. Output is written with LF line
// endings, like the original.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = (name) => readFileSync(join(here, "src", name), "utf8").replace(/\r\n/g, "\n");
const outPath = join(here, "..", "..", "public", "how-diagram.html");
const ASSETS = "/how-diagram-assets/";

// Each swap must match exactly once, so an upstream change to base.html fails
// loudly instead of silently shipping the wrong default.
const swaps = [
  ['<html lang="en">', '<html lang="en" data-cc="ink">'],
  ['<body class="cc-explainer mode-old">', '<body class="cc-explainer">'],
  [
    '<button class="tog active" data-mode="old" aria-pressed="true">Legacy System</button>',
    '<button class="tog" data-mode="old" aria-pressed="false">Legacy System</button>',
  ],
  [
    '<button class="tog" data-mode="cc" aria-pressed="false">Through Civic-Chain</button>',
    '<button class="tog active" data-mode="cc" aria-pressed="true">Through Civic-Chain</button>',
  ],
  [
    "  var mode = 'old';\n",
    "  var mode = qs.get('mode') === 'old' ? 'old' : 'cc';\n" +
      "  if (mode === 'old'){\n" +
      "    document.body.classList.add('mode-old');\n" +
      "    document.querySelectorAll('.rail-toggle .tog').forEach(function(t){ var on = t.getAttribute('data-mode') === 'old'; t.classList.toggle('active', on); t.setAttribute('aria-pressed', on ? 'true' : 'false'); });\n" +
      "  }\n",
  ],
  ["</head>", null], // filled with the skin below
];

const css = [src("light-base.css"), src("keycap.css"), src("civic-ink.css")]
  .join("\n")
  .replaceAll("{{A}}", ASSETS);
const skin =
  "<!-- ===== VARIANT SKIN: Keycap cards, Legacy aged paper + Civic-Chain deep ink. " +
  "Generated by scripts/how-diagram/build.mjs, do not hand-edit. ===== -->\n" +
  `<style id="variant-skin">\n${css}</style>\n</head>`;

let html = src("base.html");
for (const [from, to] of swaps) {
  const count = html.split(from).length - 1;
  if (count !== 1) throw new Error(`expected exactly one "${from.slice(0, 50)}" in base.html, found ${count}`);
  html = html.replace(from, () => to ?? skin);
}
if (html.includes("{{A}}")) throw new Error("unreplaced {{A}} asset placeholder");
if (/[–—]/.test(html)) throw new Error("en/em dash in output");

writeFileSync(outPath, html);
console.log(`wrote public/how-diagram.html (${html.length} chars)`);
